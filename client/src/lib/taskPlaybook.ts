/** يُطبّع العنوان: يزيل شارة «معالجة:» والرموز، للمطابقة النصّيّة. */
function normalizeTitle(title: string): string {
  return title.replace(/^🔧\s*/, '').replace(/^\[[^\]]+\]\s*/, '').replace(/معالجة:\s*/, '').trim()
}

/** يُرجع خطوات معالجة عمليّة مناسبة لعنوان المبادرة (بلا تكرار، بحدّ ٨). */
export function taskIdeasFor(title: string): TaskIdea[] {
  const norm = normalizeTitle(title)
  const matched = PLAYBOOK.filter((e) => e.keywords.some((k) => norm.includes(k)))
  if (matched.length === 0) return FALLBACK
  const seen = new Set<string>()
  const out: TaskIdea[] = []
  for (const m of matched) {
    for (const s of m.steps) {
      if (seen.has(s.t)) continue
      seen.add(s.t)
      out.push(s)
    }
  }
  return out.slice(0, 8)
}
