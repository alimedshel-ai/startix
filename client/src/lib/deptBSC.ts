// ─── Balanced Scorecard على مستوى الإدارة (INDEPENDENT_PRO) ──────
// الأبعاد الأربعة الأصلية تُعاد صياغتها لسياق الإدارة:
//   • financial → الأثر المالي المباشر للإدارة (وفر، عائد، ميزانية)
//   • customer  → «العملاء» = المستفيدون من خدمة الإدارة (داخلياً غالباً)
//   • internal  → عمليات الإدارة الأساسية اليومية
//   • learning  → تطوير قدرات فريق الإدارة نفسه
//
// لكل بُعد نُقدّم:
//   • descAr — تلميح مُفهوم للمدير في هذا التخصّص
//   • objectives[] — أمثلة أهداف (٣-٤ لكل بُعد)
//   • measures[]   — أمثلة مقاييس (KPIs)
//   • initiatives[] — أمثلة مبادرات

export type PerspectiveKey = 'financial' | 'customer' | 'internal' | 'learning'

export interface DeptPerspective {
  descAr: string
  objectives: string[]
  measures: string[]
  initiatives: string[]
}

export interface DeptBSCBank {
  perspectives: Record<PerspectiveKey, DeptPerspective>
}

// أولوية الأبعاد بحسب المسار الاستراتيجي — نُبرز البُعدَين المطابقَين.
export function perspectivePriorityForPath(path: StrategyPath | null): PerspectiveKey[] {
  if (path === 'QUICK')  return ['financial', 'internal']              // مكاسب سريعة في التكلفة والكفاءة
  if (path === 'MEDIUM') return ['customer',  'internal']              // خدمة عميل + عمليات
  return ['learning', 'customer', 'financial', 'internal']              // LONG أو null → كل الأبعاد
}

