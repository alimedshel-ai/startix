// ─── إعادة تفسير السيناريوهات لسياق إدارة المدير المستقل ─────────
// نموذج Scenario على السيرفر ثابت (revenue + profit)، لكن ما يعنيه
// كل حقل يختلف بحسب الإدارة:
//   • HR      → revenue = ميزانية الإدارة، profit = أثر (مثل تكلفة الدوران)
//   • FINANCE → revenue = تدفّق نقدي، profit = هامش تشغيلي
//   • SALES   → revenue = مبيعات، profit = هامش
//   • …
// هذا الملف يقدّم:
//   1) DeptScenarioContext — تسميات الحقلَين لكل إدارة.
//   2) DEPT_SCENARIO_PRESETS — بريستات (متفائل/محايد/متشائم) بأمثلة
//      افتراضات ومعدّلات نمو خاصة بالإدارة.

export type PresetName = 'متفائل' | 'محايد' | 'متشائم'

export interface DeptScenarioContext {
  // اسم يظهر بدل «إيراد» في المخطّط والجداول.
  revenueLabelAr: string
  // اسم يظهر بدل «ربح».
  profitLabelAr: string
  // نص شارة السياق أعلى الصفحة.
  contextHintAr: string
}

export interface DeptPreset {
  name: PresetName
  growthRate: number       // نمو سنوي (للمقياس الأول)
  marginRate: number       // نسبة (أثر / إيراد)
  assumptions: string[]    // افتراضات تخصّصية بلغة الإدارة
  hint: string             // متى يفيد هذا السيناريو للمدير؟
}

export interface DeptScenarioBank {
  context: DeptScenarioContext
  presets: Record<PresetName, DeptPreset>
}

