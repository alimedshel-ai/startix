// ─── نموذج عمل الإدارة (Department Business Model Canvas) ────────
// إعادة تفسير الكتل التسع من BMC الكلاسيكي (Osterwalder 2010) لتخدم
// المدير المستقل الذي يشرف على إدارة واحدة داخل شركة عميل.
//
// المفهوم: بدل «شركة → عملاء نهائيون» → «إدارة → عملاء داخليون».
// كل كتلة تُبقي معناها العام لكن السياق يصير عن الإدارة.
//
// شكل التخزين: BMC_<DEPT> (parallel لـ BMC الشركة الكلاسيكي).

import type { DeptCode } from './deptApi'

export type BlockKey =
  | 'segments' | 'value' | 'channels' | 'relationships' | 'revenue'
  | 'resources' | 'activities' | 'partners' | 'costs'

export interface BlockDef {
  key: BlockKey
  labelAr: string
  descAr: string          // شرح ما تعنيه الكتلة في سياق هذه الإدارة
  icon: string
  suggestions: string[]   // ٤-٦ اقتراحات جاهزة تُوضَع في textarea بضغطة
}

export type DeptBMCConfig = Record<BlockKey, BlockDef>

// ─── قوالب موحّدة تُستخدم في العنوان والوصف لكل الإدارات ─────────
const BLOCK_META: Record<BlockKey, { labelAr: string; icon: string }> = {
  segments:      { labelAr: 'شرائح العملاء الداخليين', icon: '👥' },
  value:         { labelAr: 'القيمة المُقدَّمة',        icon: '💎' },
  channels:      { labelAr: 'قنوات التوصيل',            icon: '📣' },
  relationships: { labelAr: 'نموذج العلاقة',            icon: '❤️' },
  revenue:       { labelAr: 'مصادر إثبات القيمة',       icon: '💰' },
  resources:     { labelAr: 'الموارد الرئيسية',         icon: '🏗️' },
  activities:    { labelAr: 'الأنشطة الرئيسية',         icon: '⚙️' },
  partners:      { labelAr: 'الشركاء الرئيسيون',        icon: '🤝' },
  costs:         { labelAr: 'هيكل التكاليف',            icon: '💸' },
}

function block(dept: DeptCode, key: BlockKey, descAr: string, suggestions: string[]): BlockDef {
  const _ = dept // موجود لأغراض توسّع لاحق (per-dept metadata)
  void _
  return { key, ...BLOCK_META[key], descAr, suggestions }
}

