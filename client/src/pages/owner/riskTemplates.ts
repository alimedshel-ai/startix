// القالب المطابق تطابقاً مضبوطاً (بعد trim) — للإكمال التلقائيّ وقت الكتابة/الاختيار
// من القائمة المنسدلة. صارم عمداً: لا نملأ تلقائيّاً إلّا على اسمٍ معروف بدقّة.
export function findRiskTemplate(name: string, specialty: DeptCode | null) {
  if (!specialty) return undefined
  const clean = name.trim()
  if (!clean) return undefined
  return COMMON_RISKS_BY_DEPT[specialty]?.find((t) => t.name === clean)
}

// تطبيع عربيّ: انزع بادئة الوسم «[تشخيص]/[تهديد]/[ضعف]»، والتشكيل والتطويل،
// ووحّد (أ/إ/آ→ا · ة→ه · ى→ي) — كي يطابق «[تشخيص] استقالة الموظفين» قالبَ HR.
function normalizeArabic(s: string): string {
  return s
    .replace(/^\s*\[[^\]]*\]\s*/, '')
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim()
}
function contentTokens(s: string): string[] {
  return normalizeArabic(s)
    .split(' ')
    // انزع واو الوصل البادئة (والتوظيف→التوظيف) كي تطابق الكلمة قالبها.
    .map((w) => (w.startsWith('و') && w.length >= 4 ? w.slice(1) : w))
    .filter((w) => w.length >= 3)
}

// مطابقة ذكيّة (تقاطع كلمات ≥١) — تعالج الجذر: الأسماء المستوردة «[تشخيص] …»
// لا تطابق حرفيّاً لكنّها تشارك كلمة محتوى (استقالة/توظيف/امتثال…). تُستعمَل لعرض
// الرقائق على مخاطر قائمة، لا للإكمال التلقائيّ (كي لا نملأ خطأً على تشابهٍ عابر).
export function matchRiskTemplate(name: string, specialty: DeptCode | null) {
  if (!specialty) return undefined
  const bank = COMMON_RISKS_BY_DEPT[specialty]
  if (!bank) return undefined
  const nameTokens = new Set(contentTokens(name))
  if (nameTokens.size === 0) return undefined
  let best: (typeof bank)[number] | undefined
  let bestScore = 0
  for (const t of bank) {
    const score = contentTokens(t.name).filter((w) => nameTokens.has(w)).length
    if (score > bestScore) { bestScore = score; best = t }
  }
  return bestScore >= 1 ? best : undefined
}

// مجموعة اقتراحات القسم (بلا تكرار) — لعرضٍ اختياريّ مطويّ حين لا مطابقة.
export function deptMitigationPool(specialty: DeptCode | null): string[] {
  if (!specialty) return []
  const bank = COMMON_RISKS_BY_DEPT[specialty]
  if (!bank) return []
  return [...new Set(bank.map((t) => t.mitigations[0]))]
}
