// القالب المطابق تطابقاً مضبوطاً (بعد trim) — للإكمال التلقائيّ وقت الكتابة/الاختيار
// من القائمة المنسدلة. صارم عمداً: لا نملأ تلقائيّاً إلّا على اسمٍ معروف بدقّة.
export function findRiskTemplate(name: string, specialty: DeptCode | null) {
  if (!specialty) return undefined
  const clean = name.trim()
  if (!clean) return undefined
  return COMMON_RISKS_BY_DEPT[specialty]?.find((t) => t.name === clean)
}

// تطبيع عربيّ: انزع بادئة الوسم «[تشخيص]/[تهديد]/[ضعف]»، والتشكيل والتطويل،
// ووحّد (أ/إ/آ→ا · ة→ه · ى→ي) — كي يطابق «[تشخيص] استقالة الموظفين» قالبَ HR.
function normalizeArabic(s: string): string {
  return s
    .replace(/^\s*\[[^\]]*\]\s*/, '')
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim()
}
// كلمات وقفٍ عربيّة (مُطبَّعة) — وظيفيّة لا محتوى؛ استبعادها يمنع التطابق الزائف
// (مثل «غير» التي تجعل «شيء غير موجود» يطابق «نظام قديم غير مدعوم»).
const STOPWORDS = new Set([
  'غير', 'علي', 'الي', 'هذا', 'هذه', 'ذلك', 'تلك', 'التي', 'الذي', 'بين', 'دون',
  'نحو', 'حول', 'ضمن', 'عند', 'بعد', 'قبل', 'منذ', 'لكن', 'كما', 'حيث', 'اذا',
  'مثل', 'عبر', 'كان', 'كانت', 'ايضا', 'ايّ', 'اي',
  // وصفٌ عامّ لا محتوى: مخاطر التدقيق كلها «ضعف <محور>»، فمطابقتها على «ضعف»
  // تُنتج تطابقاً زائفاً (كلّها تلتقي أوّل قالب فيه «ضعف» = تحصيل الذمم). النوع
  // الحقيقيّ في الكلمة التالية (الحوكمة/الفريق/الرقمي…) لا في «ضعف».
  'ضعف',
])
function contentTokens(s: string): string[] {
  return normalizeArabic(s)
    .split(' ')
    // انزع واو الوصل البادئة (والتوظيف→التوظيف) كي تطابق الكلمة قالبها.
    .map((w) => (w.startsWith('و') && w.length >= 4 ? w.slice(1) : w))
    .filter((w) => w.length >= 3 && !STOPWORDS.has(w))
}

type RiskTemplate = { name: string; probability: 1|2|3|4|5; impact: 1|2|3|4|5; mitigations: string[] }

// مطابقة ذكيّة عبر **كلّ الأقسام** (تقاطع كلمات ≥١) — مخاطر التشخيص عابرة للأقسام
// (توريد/أمن/تراخيص…) فلا تُقيَّد بتخصّص المدير. تخصّص المستخدم أوّلاً لأولويّة
// التعادل. تُستعمَل للعرض على مخاطر قائمة، لا للإكمال التلقائيّ (تشابهٌ عابر).
export function matchRiskTemplate(name: string, specialty: DeptCode | null): RiskTemplate | undefined {
  const nameTokens = new Set(contentTokens(name))
  if (nameTokens.size === 0) return undefined
  const ordered: RiskTemplate[] = [
    ...(specialty ? COMMON_RISKS_BY_DEPT[specialty] ?? [] : []),
    ...Object.entries(COMMON_RISKS_BY_DEPT)
      .filter(([d]) => d !== specialty)
      .flatMap(([, arr]) => arr ?? []),
  ]
  let best: RiskTemplate | undefined
  let bestScore = 0
  for (const t of ordered) {
    const score = contentTokens(t.name).filter((w) => nameTokens.has(w)).length
    if (score > bestScore) { bestScore = score; best = t }
  }
  return bestScore >= 1 ? best : undefined
}

// مجموعة اقتراحات القسم (بلا تكرار) — لعرضٍ اختياريّ مطويّ حين لا مطابقة.
export function deptMitigationPool(specialty: DeptCode | null): string[] {
  if (!specialty) return []
  const bank = COMMON_RISKS_BY_DEPT[specialty]
  if (!bank) return []
  return [...new Set(bank.map((t) => t.mitigations[0]))]
}

